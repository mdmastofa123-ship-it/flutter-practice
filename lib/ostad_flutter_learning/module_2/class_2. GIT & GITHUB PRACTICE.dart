// BASIC GIT WORKFLOW
// ------------------------------------------------------------
//
// git init
// → Project-এ Git শুরু করার জন্য
//
// git status
// → Project-এর বর্তমান Git status দেখার জন্য
//
// git add filename
// → নির্দিষ্ট একটি file staging area-তে নেওয়ার জন্য
//
// git add .
// → বর্তমান project-এর পরিবর্তিত fileগুলো staging করার জন্য
//
// git commit -m "message"
// → পরিবর্তনকে একটি checkpoint হিসেবে save করার জন্য
//
// git push
// → Local computer থেকে GitHub-এ পরিবর্তন পাঠানোর জন্য
//
// git pull
// → GitHub থেকে নতুন পরিবর্তন Local computer-এ আনার জন্য
//
// git clone
// → GitHub-এর existing repository নতুন folder/computer-এ
//   copy করে Git-এর সঙ্গে connect করার জন্য
//
// ------------------------------------------------------------
// BRANCHING
// ------------------------------------------------------------
//
// git branch practice-branch
// → নতুন branch তৈরি করে
//
// git switch practice-branch
// → নতুন branch-এ চলে যায়
//
// git push -u origin practice-branch
